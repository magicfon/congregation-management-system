const fs = require('node:fs')
const path = require('node:path')
const root = path.join(__dirname, '..')
const pkg = require('pdfjs-dist/package.json')
const dir = path.join(root, 'public', 'pdfjs', pkg.version)
fs.mkdirSync(dir, { recursive: true })
fs.copyFileSync(require.resolve('pdfjs-dist/legacy/build/pdf.worker.min.mjs'), path.join(dir, 'pdf.worker.min.mjs'))
fs.copyFileSync(require.resolve('pdfjs-dist/LICENSE'), path.join(dir, 'LICENSE'))
console.log(`PDF reader worker prepared (${pkg.version})`)
